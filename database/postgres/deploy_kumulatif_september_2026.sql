  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "mesin_slug" VARCHAR(100) NOT NULL,
  "mesin_id" INT NOT NULL,
  "bulan" INT NOT NULL CHECK ("bulan" BETWEEN 1 AND 12),
  "tahun" INT NOT NULL CHECK ("tahun" BETWEEN 2020 AND 2100),
  "periode" INT NOT NULL CHECK ("periode" IN (1, 2)),
  "document_hash" VARCHAR(64) NOT NULL,
  "operator_id" INT NULL REFERENCES "users"("id_user") ON DELETE SET NULL,
  "operator_signed_at" TIMESTAMP NULL,
  "operator_token" VARCHAR(64) UNIQUE NULL,
  "spv_id" INT NULL REFERENCES "users"("id_user") ON DELETE SET NULL,
  "spv_signed_at" TIMESTAMP NULL,
  "spv_token" VARCHAR(64) UNIQUE NULL,
  "status" VARCHAR(20) NOT NULL DEFAULT 'draft',
  "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMP NULL,
  UNIQUE ("mesin_slug", "mesin_id", "bulan", "tahun", "periode")
);

CREATE INDEX IF NOT EXISTS "idx_aps_operator_token" 

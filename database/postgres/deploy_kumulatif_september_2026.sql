  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "mesin_id" INTEGER NOT NULL REFERENCES "mesin"("id") ON DELETE RESTRICT,
  "status" VARCHAR(20) NOT NULL DEFAULT 'DEAKTIVASI' CHECK ("status" = 'DEAKTIVASI'),
  "started_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "ended_at" TIMESTAMP NULL,
  "reason" VARCHAR(255) NOT NULL,
  "notes" TEXT NULL,
  "action_by_user_id" INTEGER NULL REFERENCES "users"("id_user") ON DELETE SET NULL,
  "action_by_username" VARCHAR(100) NOT NULL,
  "reactivated_by_user_id" INTEGER NULL REFERENCES "users"("id_user") ON DELETE SET NULL,
  "reactivated_by_username" VARCHAR(100) NULL,
  "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ("ended_at" IS NULL OR "ended_at" >= "started_at")
);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_active_deactivation_per_machine" 
ON "riwayat_status_mesin" ("mesin_id") WHERE "ended_at" IS NULL;

CREATE INDEX IF NOT EXISTS "idx_riwayat_mesin_period" 
ON "riwayat_status_mesin" ("mesin_id", "started_at", "ended_at");


